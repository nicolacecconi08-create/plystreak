import assert from 'node:assert/strict';
import {Chess} from './dist/vendor/chess.js';
import {isSacrifice,gradeMove,checkedGrade} from './dist/move-grade.js';
import {mirrorFen} from './dist/archive.js';
const result=(pv,cp=50,depth=20)=>({cp,mate:null,depth,lines:[{pv,cp,mate:null,depth}]});
const c=new Chess('rq4k1/8/8/8/8/8/8/RR4K1 w - - 0 1'),m=c.move('Ra4');
assert.equal(isSacrifice(m,result(['a1a4','a8a4','b1b8'])),false,'counter-capture is not a sustained sacrifice');
assert.notEqual(gradeMove({move:m,before:result(['a1a4','a8a4','b1b8']),after:result([],50)}).type,'brilliant');
const forced=new Chess('7r/8/8/8/8/5k2/8/5BRK w - - 0 1');assert.equal(forced.moves().length,1);
const fm=forced.move('Bh3');assert.equal(isSacrifice(fm,result(['f1h3','h8h3','g1g2'])),false);
const offer=new Chess('6k1/5ppp/8/8/8/3B4/8/6K1 w - - 0 1').move('Bxh7+');
const pv=['d3h7','g8h7','g1f2'];
assert(isSacrifice(offer,result(pv)));
for(const invalid of [pv.slice(0,2),[...pv.slice(0,2),'g1g8'],[...pv.slice(0,2),'bad']])assert.equal(isSacrifice(offer,result(invalid)),false);
assert.equal(gradeMove({move:offer,before:result(pv),after:result([],50)}).type,'brilliant');
for(const depth of [8,16,24])assert.notEqual(gradeMove({move:offer,before:result(pv),after:result([],50,depth)}).type,'brilliant');
const black=new Chess(mirrorFen(offer.before)).move({from:'d6',to:'h2'});
assert(isSacrifice(black,result(['d6h2','g1h2','g8f7'],-50)));
assert.equal(gradeMove({move:black,before:result(['d6h2','g1h2','g8f7'],-50),after:result([],-50)}).type,'brilliant');
let calls=0;const engine={evaluate:async()=>{calls++;return calls===1?result(pv,50,24):result([],50,14);}};
const grade=await checkedGrade(engine,{move:offer,before:result(pv),after:result([],50)});
assert.equal(calls,2);assert.notEqual(grade.type,'brilliant');assert.equal(grade.verification,'changed');
console.log('PASS Brilliant: counter-captures, forced moves, truncated/illegal PV, both colors, shallow/mismatched analyses, conservative recheck.');
