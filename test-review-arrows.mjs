import assert from 'node:assert/strict';
import {Chess} from './dist/vendor/chess.js';
import {squareCenter,arrowGeometry,reviewArrows,attackArrows} from './dist/review-arrows.js';
assert.deepEqual(squareCenter('a8'),[50,50]);
assert.deepEqual(squareCenter('h1',true),[50,50]);
assert.equal(squareCenter('z9'),null);
const c=new Chess(),fen=c.fen(),played=c.move('e4');
const other=new Chess(),best=other.move('d4');
let arrows=reviewArrows({fen,played,next:best,comparison:true});
assert.deepEqual(arrows.map(a=>a.kind),['played','next']);
assert.equal(reviewArrows({fen,played,next:played,comparison:true}).length,1);
assert.equal(reviewArrows({fen:c.fen(),played,next:best,comparison:true}).length,0,'Do not draw alternatives from a different starting position');
assert.equal(reviewArrows({fen:c.fen(),previous:played}).length,1);
assert.equal(reviewArrows({fen,previous:played}).length,0,'No stale previous move');
assert.equal(reviewArrows({fen,next:{from:'e2',to:'e5'}}).length,0,'Reject illegal arrows');
assert.equal(arrowGeometry({from:'e2',to:'e2'}),null);
assert.equal((arrowGeometry({from:'g1',to:'f3'}).path.match(/L/g)||[]).length,2,'Knight elbow');
assert.equal((arrowGeometry({from:'e2',to:'e4'}).path.match(/L/g)||[]).length,1);
assert.notEqual(arrowGeometry(best).path,arrowGeometry(best,true).path);
const castle=new Chess('r3k2r/8/8/8/8/8/8/R3K2R w KQkq - 0 1');
assert.equal(reviewArrows({fen:castle.fen(),next:{from:'e1',to:'g1'}}).length,1);
const promotion=new Chess('7k/P7/8/8/8/8/8/7K w - - 0 1');
assert.equal(reviewArrows({fen:promotion.fen(),next:{from:'a7',to:'a8',promotion:'n'}})[0].promotion,'n');
console.log('PASS: arrow orientation, same-position comparison, duplicate suppression, legal moves, no stale arrows, knight elbow, castling, underpromotion');

const pinFen='4r2k/8/8/8/8/2q5/4N3/4K3 w - - 0 1';
const pinned=attackArrows(pinFen,'e2',true);
assert(pinned.some(a=>a.to==='c3'&&a.kind==='attack'));
assert(!pinned.some(a=>a.to==='c3'&&a.kind==='capture'),'Pinned knight does not have a legal capture');
const forkFen='7k/8/2q1r3/8/3N4/8/7K/8 w - - 0 1';
assert.equal(attackArrows(forkFen,'d4').filter(a=>a.kind==='capture').length,2);
assert.equal(attackArrows(forkFen.replace(' w ',' b '),'d4').filter(a=>a.kind==='capture').length,0,'Respect side to move');
assert(attackArrows(new Chess().fen(),'e2',true).some(a=>a.to==='d3'&&a.kind==='control'));
assert(!attackArrows(new Chess().fen(),'e2',true).some(a=>a.to==='e3'),'Pawn advance is not an attack');
const ep='7k/8/8/3pP3/8/8/8/7K w - d6 0 2';
assert(attackArrows(ep,'d5').some(a=>a.from==='e5'&&a.to==='d6'&&a.kind==='capture'));
assert(!attackArrows('7k/8/8/8/8/8/P7/R6K w - - 0 1','a1',true).some(a=>a.to==='a3'),'No arrow through own blocker');
console.log('PASS attacks: forks, absolute pins, side to move, pawn control, en passant, ray blockers');
