import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../dist/',import.meta.url));
const walk=dir=>fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?(e.name==='updates'?[]:walk(path.join(dir,e.name))):[path.join(dir,e.name)]);
const files=walk(root).filter(p=>path.basename(p)!=='sw.js').map(p=>path.relative(root,p).replaceAll('\\','/')).sort();
const hash=crypto.createHash('sha256');hash.update(fs.readFileSync(fileURLToPath(import.meta.url)));for(const f of files){hash.update(f);hash.update(fs.readFileSync(path.join(root,f)));}
const version=hash.digest('hex').slice(0,20);
const worker=`// Generated by scripts/build-offline.mjs. Rebuild after every runtime change.
const CACHE='plystreak-offline-${version}';
const FILES=${JSON.stringify(files)};
const urls=new Set(FILES.map(p=>new URL(p,self.registration.scope).href));
self.addEventListener('install',event=>event.waitUntil((async()=>{
  const cache=await caches.open(CACHE);
  try { for(const file of FILES) { const request=new Request(new URL(file,self.registration.scope),{cache:'reload'}); const response=await fetch(request); if(!response.ok)throw Error('Offline asset unavailable'); if(response.redirected){const target=new URL(response.url),expected=new URL(request.url);const paths=[expected.pathname];if(expected.pathname.endsWith('.html'))paths.push(expected.pathname.slice(0,-5));if(expected.pathname.endsWith('/index.html'))paths.push(expected.pathname.slice(0,-10));if(target.origin!==self.location.origin||!paths.includes(target.pathname))throw Error('Unexpected offline redirect');} const headers=new Headers(response.headers);headers.delete('content-encoding');headers.delete('content-length');await cache.put(request,new Response(await response.arrayBuffer(),{status:response.status,headers})); } }
  catch(error){await caches.delete(CACHE);throw error;}
})()));
self.addEventListener('activate',event=>event.waitUntil((async()=>{
  for(const name of await caches.keys())if(name.startsWith('plystreak-offline-')&&name!==CACHE)await caches.delete(name);
})()));
self.addEventListener('fetch',event=>{
  if(event.request.method!=='GET')return;
  const url=new URL(event.request.url);if(url.origin!==self.location.origin)return;
  if(url.pathname===new URL(self.registration.scope).pathname)url.pathname+='index.html';
  url.search='';url.hash='';if(!urls.has(url.href))return;
  event.respondWith((async()=>{const cache=await caches.open(CACHE);return (await cache.match(url.href))||fetch(event.request);})());
});
`;
fs.writeFileSync(path.join(root,'sw.js'),worker);
console.log(`Offline bundle ${version}: ${files.length} assets; core update archives excluded.`);
