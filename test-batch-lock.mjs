import assert from 'node:assert/strict';
import {withBatchLock} from './dist/batch-lock.js';
let called=0;
Object.defineProperty(globalThis,'navigator',{configurable:true,value:{locks:{request:async(name,options,callback)=>{assert.equal(name,'plystreak-batch');assert.equal(options.ifAvailable,true);return callback(null)}}}});
assert.equal(await withBatchLock(()=>called++),null);assert.equal(called,0);
navigator.locks.request=async(_name,_options,callback)=>callback({name:'plystreak-batch'});
assert.equal(await withBatchLock(()=>++called),1);assert.equal(called,1);
console.log('PASS batch lock prevents duplicate work and allows the owner');
import {approvedQueue} from './dist/batch-consent.js';
const job={id:'batch-test',ids:['a','b']},records=['a','b'];
const save=async()=>{},unexpected=()=>assert.fail('Repeated consent prompt');
const ask=async(user,count)=>{assert.equal(user,'test');assert.equal(count,2);return false};
assert.deepEqual(await approvedQueue(job,records,{ask,save}),{pending:[],deferred:true});
assert.deepEqual(await approvedQueue(job,records,{ask:unexpected,save}),{pending:[],deferred:true});
assert.deepEqual(await approvedQueue(job,records,{manual:true,ask:async()=>true,save}),{pending:records,deferred:false});
job.ids.push('c');records.push('c');
assert.deepEqual(await approvedQueue(job,records,{ask:async(_,count)=>{assert.equal(count,1);return false},save}),{pending:['a','b'],deferred:true});
assert.deepEqual(await approvedQueue(job,[null,null,null],{ask:unexpected,save}),{pending:[],deferred:false});
